#!/usr/bin/env python3
"""Regenerate the "math behind it" section of projects/oscilloscope.html from the
"## Theory and math" chapter of the Oscilloscope repository's README.

    (cd tools/math && npm install)                 # once: installs KaTeX
    pip install markdown                           # once
    python3 tools/math/build_math.py ../Oscilloscope/README.md

Every equation is rendered to static HTML by KaTeX, so the page needs no
JavaScript to show math; any TeX error stops the build. The page only needs
assets/vendor/katex/katex.min.css (and its fonts) for the math styling.
The section is written between the MATH:START and MATH:END markers.
"""
import html
import json
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

import markdown

HERE = Path(__file__).resolve().parent
SITE = HERE.parent.parent
PAGE = SITE / "projects" / "oscilloscope.html"
START, END = "<!-- MATH:START (generated by tools/math/build_math.py) -->", "<!-- MATH:END -->"
SECTION_NO = 5


def github_slug(heading):
    """The anchor GitHub generates for a Markdown heading."""
    s = heading.strip().lower()
    s = "".join(c for c in s if c in " -_" or unicodedata.category(c)[0] in "LN")
    return s.replace(" ", "-")


def site_id(heading):
    """Short anchors for the site: 'T4.5 Software ...' -> 't4-5', 'T1. Laplace ...' -> 't1'."""
    m = re.match(r"T(\d+)(?:\.(\d+))?", heading.strip())
    if m:
        return f"t{m.group(1)}" + (f"-{m.group(2)}" if m.group(2) else "")
    return "math-" + github_slug(heading)


def render(maths):
    proc = subprocess.run(["node", str(HERE / "render.js")], input=json.dumps(
        [{"tex": t, "display": d} for t, d in maths]), capture_output=True, text=True, check=True)
    out = json.loads(proc.stdout)
    errors = [(maths[i][0], r["error"]) for i, r in enumerate(out) if "error" in r]
    for tex, err in errors:
        print(f"KaTeX error: {err}\n    in: {tex[:200]}", file=sys.stderr)
    if errors:
        sys.exit(f"{len(errors)} equation(s) failed to render")
    return [r["html"] for r in out]


def md_to_html(md_text, anchors):
    """GitHub Markdown with ```math blocks and $`...`$ inline math -> site HTML."""
    maths = []

    def keep(tex, display):
        maths.append((tex.strip(), display))
        return f"@@MATH{len(maths) - 1}@@"

    md_text = re.sub(r"```math\n(.*?)\n```", lambda m: "\n" + keep(m.group(1), True) + "\n", md_text, flags=re.S)
    md_text = re.sub(r"\$`(.+?)`\$", lambda m: keep(m.group(1), False), md_text)
    if re.search(r"(?<![\\`])\$[^$\n]+\$", md_text):
        sys.exit("found bare $...$ math; use $`...`$ (GitHub-safe) instead")

    body = markdown.markdown(md_text, extensions=["tables", "fenced_code", "sane_lists"])
    rendered = render(maths) if maths else []
    body = re.sub(r"<p>@@MATH(\d+)@@</p>", lambda m: f'<div class="math-display">{rendered[int(m.group(1))]}</div>', body)
    body = re.sub(r"@@MATH(\d+)@@", lambda m: rendered[int(m.group(1))], body)

    body = body.replace("<table>", '<div class="table-wrap"><table class="spec">').replace("</table>", "</table></div>")
    body = re.sub(r"<blockquote>\s*", '<div class="callout">', body).replace("</blockquote>", "</div>")
    body = re.sub(r"<h4>(.*?)</h4>", lambda m: f'<h4 class="math-h4" id="{site_id(html.unescape(re.sub("<[^>]+>", "", m.group(1))))}">{m.group(1)}</h4>', body)
    body = re.sub(r'href="#([^"]+)"', lambda m: f'href="#{anchors.get(m.group(1), m.group(1))}"', body)
    body = re.sub(r'<a href="(https?://[^"]+)">', r'<a href="\1" target="_blank" rel="noopener">', body)
    return body


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    readme = Path(sys.argv[1]).read_text(encoding="utf-8")
    m = re.search(r"^## Theory and math\n(.*?)(?=^## )", readme, flags=re.S | re.M)
    if not m:
        sys.exit("no '## Theory and math' chapter found")
    chapter = m.group(1)

    parts = re.split(r"^### ", chapter, flags=re.M)
    intro, sections = parts[0], [p.split("\n", 1) for p in parts[1:]]
    anchors = {}
    for title, body in sections:
        anchors[github_slug(title)] = site_id(title)
        for h in re.findall(r"^#### (.+)$", body, flags=re.M):
            anchors[github_slug(h)] = site_id(h)

    # Intro: the bullet list becomes cards, everything else is converted as is.
    cards = []
    for title, href, desc in re.findall(r"^- \[(.+?)\]\(#(.+?)\): (.+)$", intro, flags=re.M):
        num, name = title.split(". ", 1)
        cards.append(f'<a href="#{anchors.get(href, href)}"><span class="k">{html.escape(num)}</span>'
                     f'<b>{html.escape(name)}</b><span>{html.escape(desc[0].upper() + desc[1:])}</span></a>')
    intro_rest = re.sub(r"^- \[.+?\]\(#.+?\): .+\n?", "", intro, flags=re.M)
    lead, _, results = intro_rest.partition("**Key results**")

    out = [START,
           f'<section class="pj-section" id="math">',
           '  <div class="wrap">',
           f'    <h2><span class="no">{SECTION_NO}</span>The math behind it</h2>',
           '    <div class="math-intro">',
           md_to_html(lead, anchors),
           f'      <nav class="math-toc" aria-label="Math sections">{"".join(cards)}</nav>',
           '      <h3 class="math-h4">Key results</h3>' if results else "",
           md_to_html(results, anchors) if results else "",
           '    </div>']
    for title, body in sections:
        out += [f'    <div class="pj-sub" id="{site_id(title)}">',
                f'      <h3>{html.escape(title.strip())}</h3>',
                f'      <div class="math-body">{md_to_html(body, anchors)}</div>',
                '    </div>']
    out += ['  </div>', '</section>', END]
    section = "\n".join(x for x in out if x)

    page = PAGE.read_text(encoding="utf-8")
    if START not in page or END not in page:
        sys.exit(f"markers not found in {PAGE}")
    page = page[:page.index(START)] + section + page[page.index(END) + len(END):]
    PAGE.write_text(page, encoding="utf-8")
    n = section.count('class="katex"')
    print(f"wrote {len(sections)} sections, {n} equations, {len(section) // 1024} KB -> {PAGE.relative_to(SITE)}")


if __name__ == "__main__":
    main()
