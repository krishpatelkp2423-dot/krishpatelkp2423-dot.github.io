#!/usr/bin/env python3
"""Regenerate the "math behind it" section of projects/oscilloscope.html from
tools/math/oscilloscope-math.md, a short version of the "Theory and math"
chapter in the Oscilloscope repository's README.

    (cd tools/math && npm install)                 # once: installs KaTeX
    pip install markdown                           # once
    python3 tools/math/build_math.py

Every equation is rendered to static HTML by KaTeX, so the page needs no
JavaScript to show math; any TeX error stops the build. The page only needs
assets/vendor/katex/katex.min.css (and its fonts) for the math styling.
The section is written between the MATH:START and MATH:END markers.

Source format: an intro paragraph, then one "### " heading per card. Math is
written as on GitHub: $`...`$ inline and ```math blocks for display.
"""
import html
import json
import re
import subprocess
import sys
from pathlib import Path

import markdown

HERE = Path(__file__).resolve().parent
SITE = HERE.parent.parent
SOURCE = HERE / "oscilloscope-math.md"
PAGE = SITE / "projects" / "oscilloscope.html"
START, END = "<!-- MATH:START (generated by tools/math/build_math.py) -->", "<!-- MATH:END -->"
SECTION_NO = 5


def render(maths):
    proc = subprocess.run(["node", str(HERE / "render.js")], input=json.dumps(
        [{"tex": t, "display": d} for t, d in maths]), capture_output=True, text=True, check=True)
    out = json.loads(proc.stdout)
    errors = [(maths[i][0], r["error"]) for i, r in enumerate(out) if "error" in r]
    for tex, err in errors:
        print(f"KaTeX error: {err}\n    in: {tex[:200]}", file=sys.stderr)
    if errors:
        sys.exit(f"{len(errors)} equation(s) failed to render")
    return [r["html"] for r in out]


def md_to_html(md_text):
    """GitHub Markdown with ```math blocks and $`...`$ inline math -> site HTML."""
    maths = []

    def keep(tex, display):
        maths.append((tex.strip(), display))
        return f"@@MATH{len(maths) - 1}@@"

    md_text = re.sub(r"```math\n(.*?)\n```", lambda m: "\n" + keep(m.group(1), True) + "\n", md_text, flags=re.S)
    md_text = re.sub(r"\$`(.+?)`\$", lambda m: keep(m.group(1), False), md_text)
    if re.search(r"(?<![\\`])\$[^$\n]+\$", md_text):
        sys.exit("found bare $...$ math; use $`...`$ (GitHub-safe) instead")

    body = markdown.markdown(md_text, extensions=["tables", "fenced_code", "sane_lists"])
    rendered = render(maths) if maths else []
    body = re.sub(r"<p>@@MATH(\d+)@@</p>", lambda m: f'<div class="math-display">{rendered[int(m.group(1))]}</div>', body)
    body = re.sub(r"@@MATH(\d+)@@", lambda m: rendered[int(m.group(1))], body)

    body = body.replace("<table>", '<div class="table-wrap"><table class="spec">').replace("</table>", "</table></div>")
    body = re.sub(r"<blockquote>\s*", '<div class="callout">', body).replace("</blockquote>", "</div>")
    body = re.sub(r'<a href="(https?://[^"]+)">', r'<a href="\1" target="_blank" rel="noopener">', body)
    return body


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else SOURCE
    text = source.read_text(encoding="utf-8")
    parts = re.split(r"^### ", text, flags=re.M)
    intro, cards = parts[0], [p.split("\n", 1) for p in parts[1:]]
    if not cards:
        sys.exit(f"no '### ' sections in {source}")

    # A trailing paragraph after the last card (the link to the full chapter) goes below the grid.
    last_title, last_body = cards[-1]
    last_body, sep, outro = last_body.rstrip().rpartition("\n\n")
    if not (sep and "github.com" in outro and "\n" not in outro.strip()):
        last_body, outro = cards[-1][1], ""
    cards[-1] = [last_title, last_body]

    out = [START,
           '<section class="pj-section" id="math">',
           '  <div class="wrap">',
           f'    <h2><span class="no">{SECTION_NO}</span>The math behind it</h2>',
           f'    <div class="math-intro">{md_to_html(intro)}</div>',
           '    <div class="math-grid">']
    for i, (title, body) in enumerate(cards, 1):
        out += ['      <div class="box math-card">',
                f'        <span class="k">{i:02d}</span>',
                f'        <h3>{html.escape(title.strip())}</h3>',
                f'        <div class="math-body">{md_to_html(body)}</div>',
                '      </div>']
    out += ['    </div>']
    if outro:
        out += [f'    <div class="math-more">{md_to_html(outro)}</div>']
    out += ['  </div>', '</section>', END]
    section = "\n".join(out)

    page = PAGE.read_text(encoding="utf-8")
    if START not in page or END not in page:
        sys.exit(f"markers not found in {PAGE}")
    page = page[:page.index(START)] + section + page[page.index(END) + len(END):]
    PAGE.write_text(page, encoding="utf-8")
    n = section.count('class="katex"')
    print(f"wrote {len(cards)} cards, {n} equations, {len(section) // 1024} KB -> {PAGE.relative_to(SITE)}")


if __name__ == "__main__":
    main()
