"""Turn the chess symbols in DejaVu Sans Bold into SVG path data for the web game.

The desktop game (github.com/krishpatelkp2423-dot/Chess_) draws its pieces with
this font, so the website pieces look the same. Each piece needs three shapes:

  solid  the filled glyph (U+265A..U+265F), including its cut-out details
  body   only the outer edge of the filled glyph (cut-outs filled in)
  line   the outline glyph (U+2654..U+2659): edges and detail lines

White pieces are drawn as a white `body` with a dark `line` on top. Black pieces
are drawn as a light `body` halo with a dark `solid` on top.

Usage:
    pip install fonttools
    python3 tools/chess/build_pieces.py path/to/DejaVuSans-Bold.ttf

It rewrites the block between the PIECES:START and PIECES:END comments in
assets/js/chess.js.
"""
import os
import re
import sys

from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

SOLID = {"k": 0x265A, "q": 0x265B, "r": 0x265C, "b": 0x265D, "n": 0x265E, "p": 0x265F}
LINE = {"k": 0x2654, "q": 0x2655, "r": 0x2656, "b": 0x2657, "n": 0x2658, "p": 0x2659}
VIEW = 100  # pieces are drawn in a 0..100 square
PAD = 0.07  # empty space around the biggest piece, as a fraction of the square

HERE = os.path.dirname(os.path.abspath(__file__))
TARGET = os.path.normpath(os.path.join(HERE, "..", "..", "assets", "js", "chess.js"))


def contours(glyph_set, glyph_name):
    """Split a glyph into its contours (lists of pen operations)."""
    pen = RecordingPen()
    glyph_set[glyph_name].draw(pen)
    out, current = [], []
    for op, args in pen.value:
        current.append((op, args))
        if op in ("closePath", "endPath"):
            out.append(current)
            current = []
    if current:
        out.append(current)
    return out


def signed_area(contour):
    """Shoelace area over all the contour's points. TrueType draws outer edges
    clockwise (negative area) and holes counter-clockwise (positive area)."""
    pts = [pt for _, args in contour for pt in args]
    return sum(x0 * y1 - x1 * y0 for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1])) / 2


def bounds(contour_list):
    xs = [x for c in contour_list for _, args in c for x, _ in args]
    ys = [y for c in contour_list for _, args in c for _, y in args]
    return min(xs), min(ys), max(xs), max(ys)


def to_svg(contour_list, transform):
    pen = SVGPathPen(None, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
    tpen = TransformPen(pen, transform)
    for contour in contour_list:
        for op, args in contour:
            getattr(tpen, op)(*args)
    return pen.getCommands()


def main(font_path):
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()

    shapes = {}
    for kind in SOLID:
        solid = contours(glyph_set, cmap[SOLID[kind]])
        line = contours(glyph_set, cmap[LINE[kind]])
        body = [c for c in solid if signed_area(c) < 0]
        shapes[kind] = {"solid": solid, "body": body, "line": line}

    # One scale for every piece (so a pawn stays smaller than a king), with
    # each piece centred on its own outline.
    all_contours = [c for s in shapes.values() for part in s.values() for c in part]
    x0, y0, x1, y1 = bounds(all_contours)
    size = max(x1 - x0, y1 - y0) / (1 - 2 * PAD)
    scale = VIEW / size
    cy = (y0 + y1) / 2

    lines = []
    for kind, s in shapes.items():
        bx0, _, bx1, _ = bounds(s["solid"] + s["line"])
        cx = (bx0 + bx1) / 2
        # flip y (fonts point up, SVG points down) and centre in the square
        transform = (scale, 0, 0, -scale, VIEW / 2 - cx * scale, VIEW / 2 + cy * scale)
        parts = ", ".join('%s: "%s"' % (name, to_svg(s[name], transform)) for name in ("solid", "body", "line"))
        lines.append("    %s: { %s }," % (kind, parts))

    block = "  var PIECES = {\n" + "\n".join(lines) + "\n  };\n"
    with open(TARGET, encoding="utf-8") as f:
        source = f.read()
    pattern = re.compile(r"// PIECES:START[^\n]*\n.*?// PIECES:END", re.S)
    replacement = "// PIECES:START (generated by tools/chess/build_pieces.py)\n" + block + "  // PIECES:END"
    new, count = pattern.subn(lambda m: replacement, source)
    if count != 1:
        sys.exit("Couldn't find the PIECES:START / PIECES:END markers in " + TARGET)
    with open(TARGET, "w", encoding="utf-8") as f:
        f.write(new)
    print("Updated %s (%d bytes of piece data)" % (TARGET, len(block)))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
